// Spanish for the whole site (Chris 2026-11-24): every string the site shows (src/i18n/strings-en.json, collected by
// scripts/harvest-strings.cjs) has a Spanish translation or is a name kept in English on purpose (keep-english.txt);
// the build writes a Spanish page for every route; legal pages have Spanish texts that say the English governs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = f => readFileSync(join(root, f), 'utf8');

test('every string the site shows has Spanish, or is a name kept in English', async () => {
  const { tr } = await import('../src/i18n/translate.js');
  const all = JSON.parse(read('src/i18n/strings-en.json'));
  const keep = new Set(read('src/i18n/keep-english.txt').split('\n').filter(Boolean));
  const missing = all.filter(s => tr(s) == null && !keep.has(s));
  assert.deepEqual(missing, []);
  assert.ok(all.length > 800);
});

test('patterns: prices, counts and plan names', async () => {
  const { tr } = await import('../src/i18n/translate.js');
  assert.equal(tr('$150 / month'), '$150 / mes');
  assert.equal(tr('Everything in Always Free, plus'), 'Todo lo de Siempre gratis, y además');
  assert.equal(tr('Growth · $150/mo'), 'Growth · $150/mes');
  assert.equal(tr('Testing 7/42'), 'Probando 7/42');
  assert.equal(tr('  Start free  '), '  Empieza gratis  ', 'surrounding spaces are kept');
  assert.equal(tr('iPhone 14 Pro'), null, 'model names stay as they are');
});

test('translateHtml: text and labels in Spanish, scripts and the Autograding page untouched, links stay in Spanish', async () => {
  const { translateHtml } = await import('../src/i18n/translate.js');
  const html = '<a href="/pricing" aria-label="Compare plans">Start free</a><script>var x="Start free"</script>'
    + '<div data-no-tr=""><p>Start free</p><div><span>Pricing</span></div></div><p>Pricing</p>';
  const out = translateHtml(html);
  assert.match(out, /<a href="\/es\/pricing" aria-label="Compara los planes">Empieza gratis<\/a>/);
  assert.match(out, /var x="Start free"/);
  assert.match(out, /<div data-no-tr=""><p>Start free<\/p><div><span>Pricing<\/span><\/div><\/div><p>Precios<\/p>/);
});

test('every legal page has a Spanish text that says the English version governs', () => {
  const en = readdirSync(join(root, 'src/legal')).filter(f => f.endsWith('.txt'));
  const es = new Set(readdirSync(join(root, 'src/legal/es')));
  for (const f of en) {
    assert.ok(es.has(f), `src/legal/es/${f}`);
    const t = read('src/legal/es/' + f);
    assert.match(t, /^Version: /, f);
    assert.match(t, /prevalece la versión en inglés/, f);
  }
});

test('the dictionary is built from the .tsv tables (no hand edits)', () => {
  assert.match(read('src/i18n/es.js'), /^\/\/ GENERATED by scripts\/build-es\.py/);
});

test('asset paths are absolute, so pages under /es/ load the same images and models', () => {
  const walk = d => readdirSync(join(root, d), { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]);
  const bad = walk('src').filter(f => /\.(jsx?|css)$/.test(f) && !f.includes('autograding'))
    .filter(f => /['"`(]assets\//.test(read(f)));
  assert.deepEqual(bad, []);
});
