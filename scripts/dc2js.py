#!/usr/bin/env python3
"""Convert the approved Claude Design boards (Main.dc.html, Hero.dc.html) into website modules:
src/autograding/template.js (HTML string renderers) and src/autograding/vals.js (the copy and links, EN/ES).
Supports the subset the boards use: {{expr}}, <sc-for list as>, <sc-if value>, <dc-import name="Hero">.

Usage: download the board files (Main.dc.html, Hero.dc.html) from the Claude Design canvas
("inphox Autograding", claude.ai artifact 111dee46-ff8a-447c-81e9-835df7846b96) into a folder, then:
    python3 scripts/dc2js.py <that folder> src/autograding
and commit the regenerated src/autograding/template.js and vals.js (ag.css is copied by hand, with html/body
rules scoped to .ag)."""
import re, sys, os
proj, out = sys.argv[1], sys.argv[2]
main = open(os.path.join(proj, 'Main.dc.html')).read()
hero = open(os.path.join(proj, 'Hero.dc.html')).read()

def section(html, start, end_before=None):
    a = html.index(start)
    if end_before:
        b = html.index(end_before, a)
    else:
        b = html.rindex('</section>') + len('</section>')
    return html[a:b]

main_t = section(main, '<section id="top"', '<footer')
hero_t = section(hero, '<section class="hx"')

# site-specific edits before conversion
main_t = main_t.replace('<p class="ag-mono" style="margin: 14px 0 0; font-size: 13px; color: #b9af9f">{{t.refLine}} <span style="color: #e0a273">{{refCode}}</span></p>',
                        '<sc-if value="{{refCode}}"><p class="ag-mono" style="margin: 14px 0 0; font-size: 13px; color: #b9af9f">{{t.refLine}} <span style="color: #e0a273">{{refCode}}</span></p></sc-if>')
assert '<sc-if value="{{refCode}}">' in main_t, 'refLine not found'
main_t = main_t.replace('<div class="{{normLensCls}}"', '<div data-norm="lens" class="{{normLensCls}}"')
main_t = main_t.replace('<div class="{{normEdgeCls}}"', '<div data-norm="edge" class="{{normEdgeCls}}"')
main_t = main_t.replace('<input type="range"', '<input data-norm="range" type="range"')
main_t = main_t.replace('https://inphox.net/pricing', '/pricing').replace('https://www.inphox.net/pricing', '/pricing')

def convert(t, bound=()):
    t = re.sub(r'\s(onClick|onInput|onChange)="\{\{[^}]*\}\}"', '', t)
    t = t.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')
    t = re.sub(r'<dc-import name="Hero"[^>]*></dc-import>', '${hero}', t)
    t = re.sub(r'<sc-for list="\{\{\s*(.*?)\s*\}\}" as="(\w+)"[^>]*>', lambda m: '${(%s || []).map((%s) => `' % (m.group(1), m.group(2)), t)
    t = t.replace('</sc-for>', "`).join('')}")
    t = re.sub(r'<sc-if value="\{\{\s*(.*?)\s*\}\}"[^>]*>', lambda m: '${(%s) ? `' % m.group(1), t)
    t = t.replace('</sc-if>', "` : ''}")
    t = re.sub(r'\{\{\s*(.*?)\s*\}\}', lambda m: '${e(%s)}' % m.group(1), t)
    return t

def roots(t):
    names = set(re.findall(r'\{\{\s*([A-Za-z_]\w*)', t)) | set(re.findall(r'list="\{\{\s*([A-Za-z_]\w*)', t)) | set(re.findall(r'value="\{\{\s*([A-Za-z_]\w*)', t))
    loop = set(re.findall(r'as="(\w+)"', t))
    return sorted(n for n in names - loop if n not in ('false', 'true'))

m_roots, h_roots = roots(main_t), roots(hero_t)
js = ['// GENERATED by dc2js.py from the approved Claude Design boards (Main.dc.html, Hero.dc.html). Do not edit by hand:',
      '// change the board, then regenerate. Renders HTML strings so the build prerender and the browser show the same page.',
      "const e = v => v == null || v === false ? '' : String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\"/g, '&quot;');",
      '',
      'export function renderHero(v) {',
      '  const { %s } = v;' % ', '.join(h_roots),
      '  return `' + convert(hero_t) + '`;',
      '}',
      '',
      'export function renderMain(v, hero) {',
      '  const { %s } = v;' % ', '.join(m_roots),
      '  return `' + convert(main_t) + '`;',
      '}',
      '']
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'template.js'), 'w').write('\n'.join(js))

def body(html, start_marker):
    s = html[html.index(start_marker):]
    s = s[:s.index('\n  }\n}\n</script>')]
    return s

mb = body(main, '    const T = {')
mb = mb.replace('this.setState', 'noop').replace('this.state.menu', 'false')
mb = mb.replace("const utm = (c) => 'ref=' + encodeURIComponent(ref) + '&utm_source=", "const utm = (c) => (ref ? 'ref=' + encodeURIComponent(ref) + '&' : '') + 'utm_source=")
mb = mb.replace("'https://inphox.net/contact?'", "'/contact?'")
assert "(ref ? 'ref='" in mb
hb = body(hero, '    const T = {')
hb = hb.replace("const utm = 'ref=' + encodeURIComponent(ref) + '&utm_source=", "const utm = (ref ? 'ref=' + encodeURIComponent(ref) + '&' : '') + 'utm_source=")
hb = hb.replace("'https://inphox.net/contact?'", "'/contact?'")
assert "(ref ? 'ref='" in hb
vals = ['// GENERATED by dc2js.py from the approved Claude Design boards: the page copy (EN/ES) and every link, with ref + UTM.',
        'const noop = () => {};',
        '',
        "export function mainVals(lang = 'en', ref = '') {",
        '  const menuOpen = false, normX = null;',
        mb,
        '}',
        '',
        "export function heroVals(lang = 'en', ref = '') {",
        hb,
        '}',
        '']
open(os.path.join(out, 'vals.js'), 'w').write('\n'.join(vals))
print('ok', len(main_t), len(hero_t), 'roots', m_roots, h_roots)
