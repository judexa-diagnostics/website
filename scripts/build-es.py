#!/usr/bin/env python3
"""Builds src/i18n/es.js (the Spanish dictionary) from the translation tables in src/i18n/es/*.tsv:
one line per string, English <TAB> Spanish. Edit the .tsv files, then run: python3 scripts/build-es.py"""
import glob, json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pairs = {}
for f in sorted(glob.glob(os.path.join(root, 'src/i18n/es/*.tsv'))):
    for n, line in enumerate(open(f, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'):
            continue
        en, sep, es = line.partition('\t')
        if not sep or not es.strip():
            raise SystemExit(f'{f}:{n}: needs English<TAB>Spanish')
        en = ' '.join(en.split()); es = es.strip()
        if en in pairs and pairs[en] != es:
            raise SystemExit(f'{f}:{n}: "{en}" translated twice differently')
        pairs[en] = es
out = ['// GENERATED by scripts/build-es.py from src/i18n/es/*.tsv. Edit the .tsv files, not this one.',
       'export const ES = ' + json.dumps(dict(sorted(pairs.items())), ensure_ascii=False, indent=0) + ';',
       "export { ES_PATTERNS } from './patterns.js';", '']
open(os.path.join(root, 'src/i18n/es.js'), 'w', encoding='utf-8').write('\n'.join(out))
print('es.js:', len(pairs), 'strings')
